CREATE TABLE os (
    id_os INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_veiculo INTEGER NOT NULL,
    data_inicio TIMESTAMP,
    data_fim TIMESTAMP,
    valor NUMERIC(12, 2) NOT NULL DEFAULT 0,

    CONSTRAINT pk_os PRIMARY KEY (id_os),
    CONSTRAINT fk_os_veiculo FOREIGN KEY (id_veiculo) REFERENCES veiculo (id_veiculo)
);

CREATE INDEX ix_os_id_veiculo ON veiculo (id_veiculo);

