CREATE TABLE os_colaborador (
    id_os_colaborador INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_os INTEGER NOT NULL,
    id_colaborador INTEGER NOT NULL,

    CONSTRAINT pk_os_colaborador PRIMARY KEY (id_os_colaborador),

    CONSTRAINT fk_os_colaborador_os FOREIGN KEY (id_os) REFERENCES os (id_os),
    CONSTRAINT fk_os_colaborador_colaborador FOREIGN KEY (id_colaborador) REFERENCES colaborador (id_colaborador)
);

CREATE INDEX ix_os_colaborador_id_os ON os (id_os);
CREATE INDEX ix_os_colaborador_id_colaborador ON colaborador (id_colaborador);
