CREATE TABLE os_insumo (
    id_os_insumo INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_os INTEGER NOT NULL,
    id_insumo INTEGER NOT NULL,
    quantidade INTEGER NOT NULL DEFAULT 1,
    valor_cobrado NUMERIC(12, 2) NOT NULL DEFAULT 0,

    CONSTRAINT pk_os_insumo PRIMARY KEY (id_os_insumo),

    CONSTRAINT fk_os_insumo_os FOREIGN KEY (id_os) REFERENCES os (id_os),
    CONSTRAINT fk_os_insumo_insumo FOREIGN KEY (id_insumo) REFERENCES insumo (id_insumo)
);

CREATE INDEX ix_os_insumo_id_os ON os (id_os);
CREATE INDEX ix_os_insumo_id_insumo ON insumo (id_insumo);