CREATE TABLE os_servico (
    id_os_servico INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_os INTEGER NOT NULL,
    id_servico INTEGER NOT NULL,
    quantidade INTEGER NOT NULL DEFAULT 1,
    valor_cobrado NUMERIC(12, 2) NOT NULL DEFAULT 0,
    descricao VARCHAR,

    CONSTRAINT pk_os_servico PRIMARY KEY (id_os_servico),

    CONSTRAINT fk_os_servico_os FOREIGN KEY (id_os) REFERENCES os (id_os),
    CONSTRAINT fk_os_servico_servico FOREIGN KEY (id_servico) REFERENCES servico (id_servico)
);

CREATE INDEX ix_os_servico_id_os ON os (id_os);
CREATE INDEX ix_os_servico_id_servico ON servico (id_servico);