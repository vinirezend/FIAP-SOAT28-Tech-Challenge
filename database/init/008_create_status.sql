CREATE TABLE status (
    id_status INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome varchar(30),

    CONSTRAINT pk_status PRIMARY KEY (id_status),
    CONSTRAINT uq_status_nome UNIQUE (nome)
);

