CREATE TABLE os_status (
    id_os_status INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_os INTEGER NOT NULL,
    id_status INTEGER NOT NULL,
    id_colaborador INTEGER NOT NULL,
    data_inclusao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_ordem_servico_status PRIMARY KEY (id_os_status),

    CONSTRAINT fk_os_status_os FOREIGN KEY (id_os) REFERENCES os (id_os),
    CONSTRAINT fk_os_status_status FOREIGN KEY (id_status) REFERENCES status (id_status),
    CONSTRAINT fk_os_status_colaborador FOREIGN KEY (id_colaborador) REFERENCES colaborador (id_colaborador)
);

CREATE INDEX ix_os_status_id_os ON os (id_os);
CREATE INDEX ix_os_status_id_status ON status (id_status);
CREATE INDEX ix_os_status_id_colaborador ON colaborador (id_colaborador);

